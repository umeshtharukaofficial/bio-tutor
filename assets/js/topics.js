// Quick access helpers
const TopicUtils = {
  getById(id) {
    return BIOLOGY_TOPICS.find(t => t.id === id);
  },
  getByGrade(grade) {
    return BIOLOGY_TOPICS.filter(t => t.grade === grade);
  },
  getAllIds() {
    return BIOLOGY_TOPICS.map(t => t.id);
  },
  getDropdownOptions() {
    return BIOLOGY_TOPICS.map(t => ({
      value: t.id,
      label: `Grade ${t.grade} — Unit ${t.unit}: ${t.title}`,
    }));
  },
};
